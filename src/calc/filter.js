// Шаг 1: Преобразование уравнений окружностей
// Для каждого маяка у нас есть уравнение:
// (x−xi)2+(y−yi)2=di2(x - x_i)^2 + (y - y_i)^2 = d_i^2(x−xi)2+(y−yi)2=di2
// Мы можем переписать его в линейную форму, вычитая уравнение для одного маяка из других и упрощая:
// 2(xi−x1)x+2(yi−y1)y=d12−di2+xi2−x12+yi2−y122(x_i - x_1)x + 2(y_i - y_1)y = d_1^2 - d_i^2 + x_i^2 - x_1^2 + y_i^2 - y_1^22(xi−x1)x+2(yi−y1)y=d12−di2+xi2−x12+yi2−y12
// Шаг 2: Применение метода наименьших квадратов
// Мы используем систему линейных уравнений, чтобы выразить координаты xxx и yyy как решение этой системы.
// Мы можем представить это в виде матричного уравнения, которое затем можно решить с помощью метода наименьших квадратов.

function leastSquares(beacons) {
  // Линейная алгебра с библиотекой numeric.js:
  const A = [];
  const B = [];

  // Базовый маяк для вычитания
  const { x: x1, y: y1, distance: d1 } = beacons[0];

  // Для каждого из остальных маяков создаем уравнение
  for (let i = 1; i < beacons.length; i++) {
    const { x: xi, y: yi, distance: di } = beacons[i];

    A.push([2 * (xi - x1), 2 * (yi - y1)]);
    B.push(
      d1 ** 2 - di ** 2 + xi ** 2 - x1 ** 2 + yi ** 2 - y1 ** 2
    );
  }

  // Решаем систему уравнений методом наименьших квадратов
  const AT = numeric.transpose(A); // Транспонированная матрица A
  const ATA = numeric.dot(AT, A);  // ATA = A^T * A
  const ATB = numeric.dot(AT, B);  // ATB = A^T * B

  // Решаем систему уравнений (ATA * X = ATB) для нахождения X (координаты x, y)
  const result = numeric.solve(ATA, ATB);

  const [x, y] = result;
  return { x, y };
}

